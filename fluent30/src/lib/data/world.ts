export interface WorldDestination {
  id: string; // shared with the passport stamp id when it exists
  nameFr: string;
  nameEn: string;
  country: string;
  accent: Accent;
  accentLabel: string;
  level: CefrLevel;
  tagline: string;
  palette: { sky: string; ground: string; accent: string; ink: string };
  landmark: Landmark;
  /** position on the stylised map (viewBox 1000 × 560) */
  pin: { x: number; y: number };
  characters: WorldCharacter[];
  /** course lessons that prove the needed skills (any of the 3 unlock ways is enough) */
  requires: string[];
  missions: Mission[];
}

// ---------- small builders (keep the data readable) ----------
const mcq = (prompt: string, options: string[], answer: number, explain: string, fr?: string): Exercise => ({ type: "mcq", prompt, options, answer, explain, fr });
const fill = (sentence: string, answers: string[], explain: string, fr?: string, hint?: string): Exercise => ({ type: "fill", sentence, answers, explain, fr, hint });
const listen = (audio: string, question: string, options: string[], answer: number, explain: string): Exercise => ({ type: "listen", audio, question, options, answer, explain });
const reorder = (answer: string, explain: string, fr?: string): Exercise => ({ type: "reorder", words: answer.split(" "), answer, explain, fr });
const tr = (from: "fr" | "en", text: string, answers: string[], explain: string): Exercise => ({ type: "translate", from, text, answers, explain });
const match = (pairs: [string, string][], explain?: string): Exercise => ({ type: "match", pairs, explain });
const fix = (sentence: string, answers: string[], explain: string): Exercise => ({ type: "fix", sentence, answers, explain });
const say = (speaker: string, en: string, fr?: string): DialogueLine => ({ speaker, en, fr });
/** The learner's turn. Choices are rotated deterministically so the right answer is not always first. */
const pick = (fr: string, ...choices: [string, boolean, string][]): DialogueLine => {
  const list = choices.map(([en, correct, why]) => ({ en, correct, why }));
  const r = [...fr].reduce((a, c) => a + c.charCodeAt(0), 0) % list.length;
  return { speaker: "You", fr, choices: [...list.slice(r), ...list.slice(0, r)] };
};
const dialogue = (intro: string, ...lines: DialogueLine[]): Exercise => ({ type: "dialogue", intro, lines });

